const assert = require('node:assert/strict');
const { quality, matchIdentity, compareIdentity, MODEL } = require('../app/static_pages/face-unlock-core.js');
const face = () => ({ box: { x: .18, y: .15, width: .64, height: .7 }, pose: { roll: 0, yaw: 0, pitch: .55 }, score: .98, landmarksVisible: true, quality: { brightness: 140, sharpness: 140, eyesOpen: .25, eyeTexture: 30, noseTexture: 15, mouthTexture: 35 } });
const valid=face();valid.source={width:640,height:854,faceWidth:210,faceHeight:290};
assert.equal(quality(valid),null);
for(const key of ['sharpness','eyesOpen','eyeTexture','noseTexture','mouthTexture']){const f=face();f.quality[key]=0;assert.equal(quality(f),null,'Uncalibrated '+key+' must not reject a detected face');}
const dark=face();dark.quality.brightness=10;assert.equal(quality(dark),null,'Brightness alone is advisory');
const wrong=face();wrong.landmarksVisible=false;assert.match(quality(wrong),/Mata/);
const small=face();small.source={width:640,height:854,faceWidth:70,faceHeight:90};assert.match(quality(small),/100/);
const lowResolution=face();lowResolution.source={width:240,height:320,faceWidth:150,faceHeight:180};assert.match(quality(lowResolution),/480/);
const tilted=face();tilted.pose.roll=35;assert.match(quality(tilted),/Luruskan/);
const weak=face();weak.score=.4;assert.match(quality(weak),/Deteksi/);
const descriptor = [1, ...Array(127).fill(0)];
const profile = { model_version: MODEL, descriptors: [descriptor, descriptor, descriptor] };
assert.equal(matchIdentity(descriptor, profile), true);
assert.equal(matchIdentity(descriptor, null), false);
assert.equal(matchIdentity(descriptor, { ...profile, model_version: 'other' }), false);
assert.equal(matchIdentity([0, 1, ...Array(126).fill(0)], profile), false);
assert.equal(matchIdentity(Array(128).fill(0), profile), false);
assert.equal(matchIdentity(Array(128).fill(NaN), profile), false);
assert.equal(matchIdentity(descriptor, { ...profile, descriptors: [descriptor] }), true);
assert.equal(matchIdentity(descriptor, { ...profile, descriptors: [descriptor,descriptor] }), false);
const closeDescriptor=[1,.4,...Array(126).fill(0)];
assert.equal(matchIdentity(closeDescriptor,profile,.35),false);
const diagnostic=compareIdentity(closeDescriptor,profile,.30);
assert.equal(diagnostic.matched,false);assert.equal(diagnostic.valid,true);assert.ok(Math.abs(diagnostic.distance-.4)<1e-9);assert.equal(diagnostic.threshold,.30);
assert.equal(compareIdentity(closeDescriptor,null,.45).valid,false);
assert.equal(matchIdentity(closeDescriptor,profile,.45),true);
assert.equal(matchIdentity(closeDescriptor,profile,.9),false);
assert.equal(matchIdentity(closeDescriptor,profile,NaN),false);
console.log('PASS: photo quality gates, invalid inputs, legacy/single-photo references, threshold and identity matching.');
